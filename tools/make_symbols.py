"""Write the N64Recomp symbol file for South Park.

Usage: python tools/make_symbols.py

Inputs:  rom/southpark.us.funcs.json   (tools/find_functions.py)
         symbols/names.southpark.us.json (tools/match_turok2.py)
         symbols/manual_names.southpark.us.txt (hand-assigned, wins)
         symbols/manual_funcs.southpark.us.txt (hand-fixed boundaries, wins)
Output:  symbols/southpark.us.syms.toml
"""
from __future__ import annotations

import collections
import json
import re

from games import ROOT, SOUTHPARK


def main() -> None:
    funcs = json.load(open(ROOT / "rom" / "southpark.us.funcs.json"))["functions"]
    names = {(n["region"], n["vram"]): n for n in json.load(open(ROOT / "symbols" / "names.southpark.us.json"))}

    manual: dict[int, str] = {}
    for line in (ROOT / "symbols" / "manual_names.southpark.us.txt").read_text(encoding="utf-8").splitlines():
        parts = line.split("#")[0].split()
        if len(parts) == 2:
            manual[int(parts[0], 16)] = parts[1]

    # Hand-fixed boundaries replace whatever was found inside their range.
    fixed: list[tuple[int, int, str]] = []
    for line in (ROOT / "symbols" / "manual_funcs.southpark.us.txt").read_text(encoding="utf-8").splitlines():
        parts = line.split("#")[0].split()
        if len(parts) == 3:
            fixed.append((int(parts[0], 16), int(parts[1], 16), parts[2]))
    for vram, size, name in fixed:
        region = SOUTHPARK.code_region(vram)
        funcs = [f for f in funcs if not (f["region"] == region.name and vram <= f["vram"] < vram + size)]
        funcs.append({"vram": vram, "size": size, "region": region.name, "kind": "func"})
        manual[vram] = name
    funcs.sort(key=lambda f: f["vram"])

    # Turok 2 carries some libultra code twice and its decomp names the second
    # copy with a _2 suffix. South Park has one copy of each; where it matched
    # the second copy, the real name is the one without the suffix. That matters:
    # N64Recomp decides by name which libultra functions the runtime replaces.
    taken = {n["name"] for n in names.values()} | set(manual.values())
    for n in names.values():
        if n["name"].endswith("_2") and n["name"][:-2] not in taken:
            n["name"] = n["name"][:-2]

    used: collections.Counter = collections.Counter()
    lines = [
        "# South Park (USA) symbols for N64Recomp. Generated by tools/make_symbols.py; do not edit.",
        "# Function boundaries come from tools/find_functions.py, names from Turok 2 (tools/match_turok2.py).",
        "",
    ]
    named = 0
    for region in SOUTHPARK.code:
        lines += ["[[section]]", f'name = "{region.name}"', f"rom = 0x{region.rom:08X}",
                  f"vram = 0x{region.vram:08X}", f"size = 0x{region.size:X}", "functions = ["]
        for f in funcs:
            if f["region"] != region.name or f["kind"] != "func":
                continue
            n = names.get((region.name, f["vram"]))
            name = manual.get(f["vram"]) or (n["name"] if n and n["name"] else f"func_{f['vram']:08X}")
            name = re.sub(r"\W", "_", name)
            used[name] += 1
            if used[name] > 1:
                name = f"{name}_{f['vram']:08X}"
            named += not name.startswith("func_")
            lines.append(f'    {{ name = "{name}", vram = 0x{f["vram"]:08X}, size = 0x{f["size"]:X} }},')
        lines += ["]", ""]
    # Data sections carry no functions; they let the recompiler read jump tables.
    for region in SOUTHPARK.data:
        lines += ["[[section]]", f'name = "{region.name}"', f"rom = 0x{region.rom:08X}",
                  f"vram = 0x{region.vram:08X}", f"size = 0x{region.size:X}", "functions = []", ""]
    out = ROOT / "symbols" / "southpark.us.syms.toml"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    total = sum(1 for f in funcs if f["kind"] == "func")
    print(f"written {out}: {total} functions, {named} named")


if __name__ == "__main__":
    main()
